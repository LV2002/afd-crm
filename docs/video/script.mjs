#!/usr/bin/env node
/**
 * Writes `script.md` — the film as a timed shot list.
 *
 * Generated rather than hand-written so it cannot drift from what the
 * video actually shows: the timings here are the same ones the renderer
 * uses, readability floor included. It is also the voiceover script if
 * anybody ever records one.
 *
 *   node docs/video/script.mjs      (or: npm run video:script)
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SCENES } from "./scenes.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));

function floor(scene){
  const parts=[]; const take=v=>{ if(typeof v==="string")parts.push(v); else if(Array.isArray(v))v.forEach(take); else if(v&&typeof v==="object")Object.values(v).forEach(take); };
  for(const [k,v] of Object.entries(scene)){ if(k==="type"||k==="hold")continue; take(v); }
  const words=parts.join(" ").split(/\s+/).filter(w=>w.length>1).length;
  const SCANNED=new Set(["sidebar","stages","roles","badges","definitions","channels","buckets"]);
  return words/((SCANNED.has(scene.type)?330:215)/60)+1.4;
}
const ts = s => `${String(Math.floor(s/60)).padStart(2,"0")}:${String(Math.round(s%60)).padStart(2,"0")}`;

function describe(s){
  switch(s.type){
    case "title": return `**${s.title}** / ${s.subtitle} / _${s.footnote}_`;
    case "outro": return `**${s.title}** / ${s.subtitle}`;
    case "chapter": return `Chapter card **${s.number} — ${s.title}**`;
    case "statement": return (s.emphasis?"**":"")+s.text+(s.emphasis?"**":"");
    case "rule": return `RULE — **${s.rule}**\n\n  ${s.detail}`;
    case "warning": return `CAREFUL — **${s.heading}**\n\n  ${s.text}\n\n  _${s.note}_`;
    case "steps": return `HOW TO — **${s.heading}**\n\n` + s.steps.map((x,i)=>`  ${i+1}. ${x}`).join("\n") + (s.note?`\n\n  _${s.note}_`:"");
    case "definitions": return s.items.map(([t,m])=>`  **${t}** — ${m}`).join("\n");
    case "contrast": return `**${s.heading}**\n\n  ${s.left.label}: ${s.left.text}  ·  is not  ·  ${s.right.label}: ${s.right.text}\n\n  _${s.note}_`;
    case "pipeline": return `Diagram: Marketing → Sales → Accounts → Academics\n\n  ${s.caption}`;
    case "gates": return `Diagram: the two gates\n\n  Gate 1 Sales → Accounts (Confirm admission; sales work stops)\n  Gate 2 Accounts → Academics (first payment clears; student created)\n\n  ${s.caption}`;
    case "sidebar": return `Diagram: the sidebar, fourteen entries\n\n  ${s.caption}`;
    case "badges": return `Diagram: the five red badges\n\n  ${s.caption}`;
    case "buckets": return `Diagram: Overdue → Due today → New → At risk\n\n  ${s.caption}`;
    case "stages": return `Diagram: the fourteen pipeline stages and their response targets\n\n  ${s.caption}`;
    case "roles": return `Diagram: the six roles\n\n  ${s.caption}`;
    case "channels": return `Diagram: the three Chats channels\n\n  ${s.caption}`;
    case "masked": return `Diagram: +91 98••••3456 → click to reveal → recorded\n\n  ${s.caption}`;
    case "help": return `**/manual**\n\n  ${s.caption}`;
    default: return s.type;
  }
}

let at = 0;
const rows = SCENES.map((s,i)=>{
  const hold = Math.max(s.hold, floor(s));
  const row = { i:i+1, start: at, hold, s };
  at += hold; return row;
});

const out = [`# The launch walkthrough — script and timing

Generated from \`docs/video/scenes.mjs\`. Do not edit this file by hand:
change the scenes and run \`npm run video:script\`.

**Total running time ${ts(at)}**, ${SCENES.length} scenes, silent, 1920×1080.

Timings assume somebody reading at a comfortable screen pace — 215 words a
minute for prose, 330 for a list that is scanned rather than read. Any scene
whose words cannot be read in its declared hold is given longer automatically,
so these are the real on-screen durations.

If you ever record a voiceover, this is the script: each row is one shot, and
the hold is how long you have.

| # | In | Hold | Scene |
|---|---|---|---|
`];
for (const r of rows) out.push(`| ${r.i} | ${ts(r.start)} | ${r.hold.toFixed(1)}s | ${r.s.type} |\n`);
out.push("\n---\n\n## Shot by shot\n\n");
for (const r of rows) {
  out.push(`### ${r.i}. ${ts(r.start)} — ${r.s.type} (${r.hold.toFixed(1)}s)\n\n${describe(r.s)}\n\n`);
}
writeFileSync(join(HERE, "script.md"), out.join(""));
console.log("wrote docs/video/script.md —", ts(at));
